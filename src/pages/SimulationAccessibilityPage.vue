<section id="challenge">
    <h2>The Challenge</h2>

    <p>
        VR training experiences often assume users can stand, reach, turn,
        manipulate motion controllers, read small text, and rely on audio cues.
        These assumptions can unintentionally exclude users with different
        accessibility needs.
    </p>

    <p>
        As part of my work on educational simulations, I reviewed accessibility
        research and design guidance for immersive technologies to better understand
        these barriers.
    </p>
</section>

<section id="findings">
    <h2>Key Findings</h2>

    <div class="results-grid">

        <div class="result-card">
            <h3>Mobility</h3>
            <p>
                Support seated experiences, alternative inputs, and avoid requiring
                specific physical movements.
            </p>
        </div>

        <div class="result-card">
            <h3>Visual Design</h3>
            <p>
                Use readable text, strong contrast, and avoid relying solely on color
                to communicate important information.
            </p>
        </div>

        <div class="result-card">
            <h3>Audio</h3>
            <p>
                Provide captions and visual alternatives for spoken instructions and
                warnings.
            </p>
        </div>

        <div class="result-card">
            <h3>Process</h3>
            <p>
                Accessibility should be considered during requirements gathering,
                design, testing, and deployment rather than added at the end.
            </p>
        </div>

    </div>
</section>

<section id="impact">
    <h2>Impact on My Work</h2>

    <p>
        This research influenced how I approach simulation architecture. Rather
        than treating VR as the only delivery method, I design systems so that
        content, interactions, and learning objectives can be adapted to different
        interfaces and accessibility requirements.
    </p>

    <div class="highlight">
        Design principle: separate the learning objective from the specific
        physical action required to complete it.
    </div>
</section>